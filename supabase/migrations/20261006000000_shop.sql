-- ---------------------------------------------------------------------------
-- Money owed, per customer and per supplier
-- ---------------------------------------------------------------------------

create view public.shop_customer_dues with (security_invoker = true) as
select
  c.id as customer_id,
  coalesce(b.due, 0) - coalesce(p.paid, 0) as due,
  b.oldest_unpaid
from public.shop_customers c
left join (
  select customer_id, sum(due) as due, min(created_at) filter (where due > 0) as oldest_unpaid
  from public.shop_bills
  where not cancelled
  group by customer_id
) b on b.customer_id = c.id
left join (
  select customer_id, sum(amount) as paid
  from public.shop_payments
  group by customer_id
) p on p.customer_id = c.id;

create view public.shop_supplier_dues with (security_invoker = true) as
select
  s.id as supplier_id,
  coalesce(pu.total, 0) as purchased,
  coalesce(pu.unpaid, 0) - coalesce(sp.paid, 0) as owed
from public.shop_suppliers s
left join (
  select supplier_id, sum(amount) as total, sum(amount - paid) as unpaid
  from public.shop_purchases
  group by supplier_id
) pu on pu.supplier_id = s.id
left join (
  select supplier_id, sum(amount) as paid
  from public.shop_supplier_payments
  group by supplier_id
) sp on sp.supplier_id = s.id;

