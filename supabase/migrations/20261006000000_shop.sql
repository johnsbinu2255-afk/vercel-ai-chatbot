-- Car shop app: one shop shared by the owner and their staff.
--
-- * People get in by email: the first person to claim the shop becomes the
--   owner, and the owner adds staff emails in Settings.
-- * Buying prices and profit live in owner-only tables, so staff can never
--   read them, not even through the API.
-- * Stock and bills change only through the functions below, so every stock
--   change is logged and a sale can never take stock below zero.

-- ---------------------------------------------------------------------------
-- Who is who
-- ---------------------------------------------------------------------------

create table public.shop_members (
  email text primary key check (email = lower(email) and position('@' in email) > 1),
  role text not null check (role in ('owner', 'staff')),
  name text not null default '',
  created_at timestamptz not null default now()
);

-- Only one owner per shop.
create unique index shop_members_single_owner on public.shop_members (role) where role = 'owner';

create function public.shop_email()
returns text
language sql
stable
as $$
  select lower(coalesce(auth.jwt() ->> 'email', ''))
$$;

create function public.shop_is_member()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.shop_members where email = public.shop_email())
$$;

create function public.shop_is_owner()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.shop_members
    where email = public.shop_email() and role = 'owner'
  )
$$;

-- What the app needs to know about the signed-in person.
create function public.shop_me()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'email', public.shop_email(),
    'role', (select role from public.shop_members where email = public.shop_email()),
    'has_owner', exists (select 1 from public.shop_members where role = 'owner')
  )
$$;

-- The very first person to open a new shop makes themselves the owner.
create function public.shop_claim_owner()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null or public.shop_email() = '' then
    raise exception 'Please sign in first';
  end if;
  if exists (select 1 from public.shop_members where role = 'owner') then
    raise exception 'This shop already has an owner';
  end if;
  insert into public.shop_members (email, role)
  values (public.shop_email(), 'owner')
  on conflict (email) do update set role = 'owner';
end;
$$;

