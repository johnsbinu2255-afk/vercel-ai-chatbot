create function public.shop_set_cost(p_product uuid, p_cost numeric)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.shop_is_owner() then
    raise exception 'Only the owner can set buying prices';
  end if;
  if p_cost is null or p_cost < 0 then
    raise exception 'Buying price cannot be negative';
  end if;
  if exists (select 1 from public.shop_product_costs where product_id = p_product and cost = p_cost) then
    return;
  end if;
  insert into public.shop_product_costs (product_id, cost, updated_at)
  values (p_product, p_cost, now())
  on conflict (product_id) do update set cost = excluded.cost, updated_at = now();
  insert into public.shop_cost_history (product_id, cost) values (p_product, p_cost);
end;
$$;

-- Add a new product (no "id") or edit one. "qty" is only used for new products;
-- "cost" is only saved when the owner sends it.
create function public.shop_save_product(p jsonb)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid := nullif(p ->> 'id', '')::uuid;
  v_qty integer := greatest(0, coalesce(nullif(p ->> 'qty', '')::integer, 0));
begin
  if not public.shop_is_member() then
    raise exception 'You are not part of this shop';
  end if;
  if coalesce(trim(p ->> 'name'), '') = '' then
    raise exception 'Product name is needed';
  end if;

  if v_id is null then
    insert into public.shop_products (name, category_id, brand, code, price, qty, reorder_level, warranty_months, fits)
    values (
      trim(p ->> 'name'),
      nullif(p ->> 'category_id', '')::bigint,
      coalesce(trim(p ->> 'brand'), ''),
      coalesce(trim(p ->> 'code'), ''),
      coalesce(nullif(p ->> 'price', '')::numeric, 0),
      v_qty,
      coalesce(nullif(p ->> 'reorder_level', '')::integer, 3),
      coalesce(nullif(p ->> 'warranty_months', '')::integer, 0),
      coalesce(trim(p ->> 'fits'), '')
    )
    returning id into v_id;
    insert into public.shop_stock_moves (product_id, kind, change, qty_after, note)
    values (v_id, 'opening', v_qty, v_qty, coalesce(p ->> 'note', ''));
  else
    update public.shop_products set
      name = trim(p ->> 'name'),
      category_id = nullif(p ->> 'category_id', '')::bigint,
      brand = coalesce(trim(p ->> 'brand'), ''),
      code = coalesce(trim(p ->> 'code'), ''),
      price = coalesce(nullif(p ->> 'price', '')::numeric, 0),
      reorder_level = coalesce(nullif(p ->> 'reorder_level', '')::integer, 3),
      warranty_months = coalesce(nullif(p ->> 'warranty_months', '')::integer, 0),
      fits = coalesce(trim(p ->> 'fits'), '')
    where id = v_id and active;
    if not found then
      raise exception 'Product not found';
    end if;
  end if;

  if public.shop_is_owner() and nullif(p ->> 'cost', '') is not null then
    perform public.shop_set_cost(v_id, (p ->> 'cost')::numeric);
  end if;

  return v_id;
end;
$$;

-- Bulk add: a list of new products in one go.
create function public.shop_add_products(p_rows jsonb)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  r jsonb;
  n integer := 0;
begin
  if jsonb_typeof(p_rows) is distinct from 'array' then
    raise exception 'Expected a list of products';
  end if;
  for r in select * from jsonb_array_elements(p_rows) loop
    perform public.shop_save_product(r - 'id');
    n := n + 1;
  end loop;
  return n;
end;
$$;

-- Hide a product (owner only). Old bills keep their history.
create function public.shop_delete_product(p_product uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.shop_is_owner() then
    raise exception 'Only the owner can delete products';
  end if;
  update public.shop_products set active = false where id = p_product;
end;
$$;

--   delivery / return : add p_qty
--   damaged           : remove p_qty
--   count             : set stock to p_qty
create function public.shop_adjust_stock(p_product uuid, p_kind text, p_qty integer, p_note text default '')
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  cur integer;
  nxt integer;
begin
  if not public.shop_is_member() then
    raise exception 'You are not part of this shop';
  end if;
  if p_kind not in ('delivery', 'count', 'return', 'damaged') then
    raise exception 'Unknown stock change: %', p_kind;
  end if;
  if p_qty is null or p_qty < 0 or (p_kind <> 'count' and p_qty = 0) then
    raise exception 'Type a quantity';
  end if;

  select qty into cur from public.shop_products where id = p_product and active for update;
  if not found then
    raise exception 'Product not found';
  end if;

  nxt := case p_kind
    when 'count' then p_qty
    when 'damaged' then greatest(0, cur - p_qty)
    else cur + p_qty
  end;

  update public.shop_products set qty = nxt where id = p_product;
  insert into public.shop_stock_moves (product_id, kind, change, qty_after, note)
  values (p_product, p_kind, nxt - cur, nxt, coalesce(p_note, ''));
  return nxt;
end;
$$;

-- Bulk "add quantity": [{ "product_id": "...", "qty": 10, "cost": 1400 }]
create function public.shop_receive_stock(p_rows jsonb)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  r jsonb;
  q integer;
  total integer := 0;
begin
  if jsonb_typeof(p_rows) is distinct from 'array' then
    raise exception 'Expected a list of products';
  end if;
  for r in select * from jsonb_array_elements(p_rows) loop
    q := nullif(r ->> 'qty', '')::integer;
    if q is null or q <= 0 then
      continue;
    end if;
    perform public.shop_adjust_stock((r ->> 'product_id')::uuid, 'delivery', q, coalesce(r ->> 'note', ''));
    if public.shop_is_owner() and nullif(r ->> 'cost', '') is not null then
      perform public.shop_set_cost((r ->> 'product_id')::uuid, (r ->> 'cost')::numeric);
    end if;
    total := total + q;
  end loop;
  if total = 0 then
    raise exception 'Type how many arrived';
  end if;
  return total;
end;
$$;

-- ---------------------------------------------------------------------------
-- Bills
-- ---------------------------------------------------------------------------

-- {
--   "customer_id": "...", "cash": 0, "upi": 7198, "card": 0,
--   "job_id": "...", "quote_id": "...",
--   "items": [{ "product_id": "...", "name": "...", "qty": 1, "price": 5499, "serial": "" }]
-- }
create function public.shop_create_bill(p jsonb)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_bill uuid;
  v_no bigint;
  v_total numeric := 0;
  v_cash numeric := greatest(0, coalesce(nullif(p ->> 'cash', '')::numeric, 0));
  v_upi numeric := greatest(0, coalesce(nullif(p ->> 'upi', '')::numeric, 0));
  v_card numeric := greatest(0, coalesce(nullif(p ->> 'card', '')::numeric, 0));
  v_customer uuid := nullif(p ->> 'customer_id', '')::uuid;
  v_job uuid := nullif(p ->> 'job_id', '')::uuid;
  v_quote uuid := nullif(p ->> 'quote_id', '')::uuid;
  it jsonb;
  v_pid uuid;
  v_qty integer;
  v_price numeric;
  v_name text;
  v_warranty integer;
  v_stock integer;
  v_item bigint;
begin
  if not public.shop_is_member() then
    raise exception 'You are not part of this shop';
  end if;
  if jsonb_typeof(p -> 'items') is distinct from 'array' or jsonb_array_length(p -> 'items') = 0 then
    raise exception 'Add at least one item';
  end if;

  for it in select * from jsonb_array_elements(p -> 'items') loop
    v_qty := nullif(it ->> 'qty', '')::integer;
    v_price := nullif(it ->> 'price', '')::numeric;
    if v_qty is null or v_qty < 1 then
      raise exception 'Quantity must be at least 1';
    end if;
    if v_price is null or v_price < 0 then
      raise exception 'Price cannot be negative';
    end if;
    v_total := v_total + v_qty * v_price;
  end loop;

  if v_cash + v_upi + v_card > v_total then
    raise exception 'Paid amount is more than the bill total';
  end if;
  if v_total - (v_cash + v_upi + v_card) > 0 and v_customer is null then
    raise exception 'Choose a customer for udhaar';
  end if;

  insert into public.shop_bills (customer_id, total, paid_cash, paid_upi, paid_card, due, job_id, quote_id)
  values (v_customer, v_total, v_cash, v_upi, v_card, v_total - (v_cash + v_upi + v_card), v_job, v_quote)
  returning id, no into v_bill, v_no;

  for it in select * from jsonb_array_elements(p -> 'items') loop
    v_pid := nullif(it ->> 'product_id', '')::uuid;
    v_qty := (it ->> 'qty')::integer;
    v_price := (it ->> 'price')::numeric;
    v_name := coalesce(nullif(trim(it ->> 'name'), ''), 'Item');
    v_warranty := 0;

    if v_pid is not null then
      select qty, name, warranty_months into v_stock, v_name, v_warranty
      from public.shop_products
      where id = v_pid and active
      for update;
      if not found then
        raise exception 'A product in this bill no longer exists';
      end if;
      if v_stock < v_qty then
        raise exception 'Only % of % in stock', v_stock, v_name;
      end if;
      update public.shop_products set qty = v_stock - v_qty where id = v_pid;
      insert into public.shop_stock_moves (product_id, kind, change, qty_after, note)
      values (v_pid, 'sale', -v_qty, v_stock - v_qty, 'Bill B-' || v_no);
    end if;

    insert into public.shop_bill_items (bill_id, product_id, name, qty, price, warranty_months, serial)
    values (v_bill, v_pid, v_name, v_qty, v_price, coalesce(v_warranty, 0), coalesce(trim(it ->> 'serial'), ''))
    returning id into v_item;

    insert into public.shop_bill_item_costs (item_id, cost)
    values (v_item, coalesce((select cost from public.shop_product_costs where product_id = v_pid), 0));
  end loop;

  if v_job is not null then
    update public.shop_jobs set status = 'billed' where id = v_job;
  end if;
  if v_quote is not null then
    update public.shop_quotes set status = 'billed' where id = v_quote;
  end if;

  return v_bill;
end;
$$;

-- Owner only: cancel a wrong bill and put its items back in stock.
create function public.shop_cancel_bill(p_bill uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  b public.shop_bills;
  it record;
  cur integer;
begin
  if not public.shop_is_owner() then
    raise exception 'Only the owner can cancel a bill';
  end if;
  select * into b from public.shop_bills where id = p_bill for update;
  if not found then
    raise exception 'Bill not found';
  end if;
  if b.cancelled then
    raise exception 'This bill is already cancelled';
  end if;

  for it in
    select product_id, qty from public.shop_bill_items
    where bill_id = p_bill and product_id is not null
  loop
    select qty into cur from public.shop_products where id = it.product_id for update;
    if found then
      update public.shop_products set qty = cur + it.qty where id = it.product_id;
      insert into public.shop_stock_moves (product_id, kind, change, qty_after, note)
      values (it.product_id, 'cancel', it.qty, cur + it.qty, 'Bill B-' || b.no || ' cancelled');
    end if;
  end loop;

  update public.shop_bills set cancelled = true where id = p_bill;
end;
$$;

